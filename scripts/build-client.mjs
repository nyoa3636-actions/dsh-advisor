/**
 * Emit the browser artifact DSH serves for this package.
 *
 * dsh-client-modules serves a package's `./client` entry as one standalone
 * bundle that registers a lazy factory with `window.__ModuleLoader__.load`. The
 * factory receives the browser module table as `require`, so this bundle must
 * not carry its own import statements: everything it needs is inlined here and
 * React comes from the module table.
 *
 * The output is deterministic, so a rebuilt bundle changes only when its source
 * does. `--check` computes the bundle without writing it and reports staleness.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** Modules in dependency order; earlier modules may be referenced by later ones. */
const MODULES = [
  "dsh/client/locale/en.js",
  "dsh/client/locale/ja.js",
  "dsh/client/settings-fields.js",
  "dsh/client/catalog.js",
  "dsh/client/panel-controller.js",
  "dsh/client/AdvisorPanel.js",
  "dsh/client/index.js",
];

function stripModuleSyntax(source, file) {
  const body = source
    .replace(/^\s*import[\s\S]*?from\s*["'][^"']+["'];?\s*$/gmu, "")
    .replace(/^\s*import\s*["'][^"']+["'];?\s*$/gmu, "")
    // A declared name stays in bundle scope once its `export` keyword is gone.
    .replace(/^\s*export\s+(?=(?:const|let|var|function|class|async)\b)/gmu, "")
    // A re-export list only publishes names that are already in bundle scope.
    .replace(/^\s*export\s*\{[^}]*\};?\s*$/gmu, "");
  const leftover = body.match(/^\s*(?:import|export)\b/mu);
  if (leftover) throw new Error(`${file}: a module statement survived stripping: ${leftover[0].trim()}`);
  return body;
}

const parts = [];
for (const file of MODULES) {
  // Normalize line endings so the emitted bundle is byte-identical on any OS.
  const source = (await readFile(join(root, file), "utf8")).replace(/\r\n/gu, "\n");
  parts.push(`// ---- ${file} ----\n${stripModuleSyntax(source, file).trim()}`);
}

const bundle = `// Generated by scripts/build-client.mjs — do not edit by hand.
window.__ModuleLoader__.load({
  id: "dsh-advisor",
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
${parts.map((part) => part.split("\n").map((line) => (line ? `    ${line}` : line)).join("\n")).join("\n")}

    exports.NS = NS;
    exports.apply = apply;
    exports.inject = inject;
    return module.exports;
  },
});
`;

const target = join(root, "dsh", "client.js");

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = await readFile(target, "utf8");
  } catch {
    current = "";
  }
  if (current !== bundle) {
    console.error("dsh/client.js is out of date; run `npm run build:client` and commit the result");
    process.exitCode = 1;
  } else {
    console.log(`client bundle is current (${bundle.length} bytes, ${MODULES.length} modules)`);
  }
} else {
  await writeFile(target, bundle, "utf8");
  console.log(`built dsh/client.js (${bundle.length} bytes, ${MODULES.length} modules)`);
}
